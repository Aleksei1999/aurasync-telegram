export function getFreeBreathingPractices(): BreathingPractice[] {
  return allBreathingPractices.filter(p => !p.isPremium);
}

export function getPremiumBreathingPractices(): BreathingPractice[] {
  return allBreathingPractices.filter(p => p.isPremium);
}
