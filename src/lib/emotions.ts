// Вспомогательные функции
export function getEmotionById(id: string): Emotion | undefined {
  return allEmotions.find(e => e.id === id);
}

export function getEmotionsByBase(base: BaseEmotion): Emotion[] {
  return allEmotions.filter(e => e.baseEmotion === base);
}

export function getFreeEmotions(): Emotion[] {
  return allEmotions.filter(e => !e.isPremium);
}

export function getPremiumEmotions(): Emotion[] {
  return allEmotions.filter(e => e.isPremium);
}

export function getRelatedEmotions(emotionId: string): Emotion[] {
  const emotion = getEmotionById(emotionId);
  if (!emotion) return [];

  // Get emotions with same base that are NOT the same emotion
  return allEmotions.filter(e =>
    e.baseEmotion === emotion.baseEmotion && e.id !== emotionId
  ).slice(0, 5);
}

export function searchEmotions(query: string): Emotion[] {
  const lowerQuery = query.toLowerCase();
  return allEmotions.filter(e =>
    e.name.toLowerCase().includes(lowerQuery) ||
    e.definition?.toLowerCase().includes(lowerQuery)
  );
}
