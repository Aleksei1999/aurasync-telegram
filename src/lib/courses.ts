export function getCourseById(id: string): Course | undefined {
  return allCourses.find((course) => course.id === id);
}

export function getFreeCourses(): Course[] {
  return allCourses.filter((course) => !course.isPremium);
}

export function getPremiumCourses(): Course[] {
  return allCourses.filter((course) => course.isPremium);
}

export function getCoursesByDuration(minDays: number, maxDays: number): Course[] {
  return allCourses.filter(
    (course) => course.durationDays >= minDays && course.durationDays <= maxDays
  );
}

export function getCoursesByCategory(category: Course['category']): Course[] {
  return allCourses.filter((course) => course.category === category);
}

export function getCourseDayContent(courseId: string, dayNumber: number): CourseDay | undefined {
  const course = getCourseById(courseId);
  return course?.days.find((day) => day.dayNumber === dayNumber);
}

