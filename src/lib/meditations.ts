export const allMeditations: Meditation[] = [
  ...morningMeditations,
  ...eveningMeditations,
  ...emotionMeditations,
];

// Вспомогательные функции
export function getMeditationsByTimeOfDay(timeOfDay: Meditation['timeOfDay']): Meditation[] {
  return allMeditations.filter(m => m.timeOfDay === timeOfDay);
}

export function getMeditationById(id: string): Meditation | undefined {
  return allMeditations.find(m => m.id === id);
}

export function getMeditationsByProtocol(protocol: PainProtocol): Meditation[] {
  return allMeditations.filter(m => m.protocols.includes(protocol));
}

export function getFreeMeditations(): Meditation[] {
  return allMeditations.filter(m => !m.isPremium);
}

export function getPremiumMeditations(): Meditation[] {
  return allMeditations.filter(m => m.isPremium);
}

export function getMeditationsByCategory(category: string): Meditation[] {
  // Map category IDs to meditation search terms
  const categoryMapping: Record<string, string[]> = {
    emotions: ['эмоции', 'тревога', 'стресс', 'грусть'],
    transitions: ['переходы', 'изменения', 'адаптация'],
    body: ['тело', 'здоровье', 'расслабление'],
    sleep: ['сон', 'вечер', 'засыпание'],
    morning: ['утро', 'энергия', 'пробуждение'],
    women: ['женское', 'цикл', 'гормоны'],
    breathing: ['дыхание'],
    courses: [],
  };

  const searchTerms = categoryMapping[category] || [];
  if (searchTerms.length === 0) return [];

  return allMeditations.filter(m =>
    searchTerms.some(term =>
      m.name.toLowerCase().includes(term) ||
      m.theme.toLowerCase().includes(term) ||
      m.technique.toLowerCase().includes(term)
    )
  );
}
